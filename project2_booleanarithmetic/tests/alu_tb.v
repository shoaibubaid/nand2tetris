
module alu_tb;

    reg [15:0] x, y;
    reg zx, nx, zy, ny, f, no;

    wire [15:0] out;
    wire zr, ng;

    integer test_count;
    integer fail_count;

    alu uut(
        .x(x),
        .y(y),
        .zx(zx),
        .nx(nx),
        .zy(zy),
        .ny(ny),
        .f(f),
        .no(no),
        .out(out),
        .zr(zr),
        .ng(ng)
    );

    // Task to apply inputs and check expected outputs
    task run_test;
        input [15:0] tx, ty;
        input tzx, tnx, tzy, tny, tf, tno;
        input [15:0] expected_out;
        input expected_zr, expected_ng;

        begin
            x = tx;
            y = ty;

            zx = tzx;
            nx = tnx;
            zy = tzy;
            ny = tny;
            f  = tf;
            no = tno;

            #10;

            test_count = test_count + 1;

            if ((out !== expected_out) ||
                (zr !== expected_zr) ||
                (ng !== expected_ng)) begin

                fail_count = fail_count + 1;

                $display("FAIL Test %0d", test_count);
                $display("  x  = %016b", x);
                $display("  y  = %016b", y);
                $display("  zx=%b nx=%b zy=%b ny=%b f=%b no=%b",
                         zx, nx, zy, ny, f, no);

                $display("  Expected: out=%016b zr=%b ng=%b",
                         expected_out, expected_zr, expected_ng);

                $display("  Actual:   out=%016b zr=%b ng=%b",
                         out, zr, ng);

                $display("----------------------------------------");
            end
        end
    endtask


    initial begin

        $dumpfile("dump.vcd");
        $dumpvars(0, alu_tb);

        test_count = 0;
        fail_count = 0;

        // =========================================
        // GROUP 1: x = 0, y = -1
        // =========================================

        run_test(16'b0000000000000000, 16'b1111111111111111, 1,0,1,0,1,0, 16'b0000000000000000, 1,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 1,1,1,1,1,1, 16'b0000000000000001, 0,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 1,1,1,0,1,0, 16'b1111111111111111, 0,1);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,0,1,1,0,0, 16'b0000000000000000, 1,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 1,1,0,0,0,0, 16'b1111111111111111, 0,1);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,0,1,1,0,1, 16'b1111111111111111, 0,1);
        run_test(16'b0000000000000000, 16'b1111111111111111, 1,1,0,0,0,1, 16'b0000000000000000, 1,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,0,1,1,1,1, 16'b0000000000000000, 1,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 1,1,0,0,1,1, 16'b0000000000000001, 0,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,1,1,1,1,1, 16'b0000000000000001, 0,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 1,1,0,1,1,1, 16'b0000000000000000, 1,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,0,1,1,1,0, 16'b1111111111111111, 0,1);
        run_test(16'b0000000000000000, 16'b1111111111111111, 1,1,0,0,1,0, 16'b1111111111111110, 0,1);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,0,0,0,1,0, 16'b1111111111111111, 0,1);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,1,0,0,1,1, 16'b0000000000000001, 0,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,0,0,1,1,1, 16'b1111111111111111, 0,1);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,0,0,0,0,0, 16'b0000000000000000, 1,0);
        run_test(16'b0000000000000000, 16'b1111111111111111, 0,1,0,1,0,1, 16'b1111111111111111, 0,1);


        // =========================================
        // GROUP 2: x = 17, y = 3
        // =========================================

        run_test(16'b0000000000010001, 16'b0000000000000011, 1,0,1,0,1,0, 16'b0000000000000000, 1,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 1,1,1,1,1,1, 16'b0000000000000001, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 1,1,1,0,1,0, 16'b1111111111111111, 0,1);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,0,1,1,0,0, 16'b0000000000010001, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 1,1,0,0,0,0, 16'b0000000000000011, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,0,1,1,0,1, 16'b1111111111101110, 0,1);
        run_test(16'b0000000000010001, 16'b0000000000000011, 1,1,0,0,0,1, 16'b1111111111111100, 0,1);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,0,1,1,1,1, 16'b1111111111101111, 0,1);
        run_test(16'b0000000000010001, 16'b0000000000000011, 1,1,0,0,1,1, 16'b1111111111111101, 0,1);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,1,1,1,1,1, 16'b0000000000010010, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 1,1,0,1,1,1, 16'b0000000000000100, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,0,1,1,1,0, 16'b0000000000010000, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 1,1,0,0,1,0, 16'b0000000000000010, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,0,0,0,1,0, 16'b0000000000010100, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,1,0,0,1,1, 16'b0000000000001110, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,0,0,1,1,1, 16'b1111111111110010, 0,1);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,0,0,0,0,0, 16'b0000000000000001, 0,0);
        run_test(16'b0000000000010001, 16'b0000000000000011, 0,1,0,1,0,1, 16'b0000000000010011, 0,0);


        // =========================================
        // FINAL SUMMARY
        // =========================================

        $display("");
        $display("========================================");
        $display("             ALU TEST SUMMARY           ");
        $display("========================================");
        $display("Total tests : %0d", test_count);
        $display("Failed tests: %0d", fail_count);
        $display("Passed tests: %0d", test_count - fail_count);

        if (fail_count == 0)
            $display("ALL TESTS PASSED!");
        else
            $display("SOME TESTS FAILED!");

        $display("========================================");

        $finish;
    end

endmodule
