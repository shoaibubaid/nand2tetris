        .clk(clk),
        .in(in),
        .load(load),
        .address(address),
        .out(out)
    );

    initial begin
        $dumpfile("dump.vcd");
        $dumpvars(0, ram16k_tb);
    end

    task tick_op;
        begin
            // Let address, load, and the hierarchical write decoder settle
            // BEFORE the active clock edge reaches the RAM registers.
            #1;

            // Rising edge: the selected RAM4K bank captures the input.
            clk = 1'b1;
            #1;

            // Update the reference model after the write edge.
            if (load) begin
                expected_mem[address] = in;
                valid[address] = 1'b1;
            end
        end
    endtask

    task tock_op;
        begin
            clk = 1'b0;
            #1;
        end
    endtask

    task eval_op;
        begin
            #1;
        end
    endtask

    task check_output;
        begin
            #1;
            if (valid[address]) begin
                tests = tests + 1;
                if (out !== expected_mem[address]) begin
                    failures = failures + 1;
                    $display(
                        "FAIL: addr=%0d expected=%h got=%h time=%0t",
                        address, expected_mem[address], out, $time
                    );
                end
                else begin
                    $display(
                        "PASS: addr=%0d data=%h time=%0t",
                        address, out, $time
                    );
                end
            end
            else begin
                $display(
                    "SKIP: addr=%0d uninitialized (out=%h)",
                    address, out
                );
            end
        end
    endtask

