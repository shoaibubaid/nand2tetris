    // Uninitialized locations are skipped because their expected value is X.
    task check_output;
        begin
            #1;
            if (valid[address] === 1'b1) begin
                tests = tests + 1;
                if (out !== expected_mem[address]) begin
                    failures = failures + 1;
                    $display(
                        "FAIL at t=%0t addr=%0d in=%h load=%b expected=%h got=%h",
                        $time, address, in, load,
                        expected_mem[address], out
                    );
                end
                else begin
                    $display(
                        "PASS at t=%0t addr=%0d out=%h",
                        $time, address, out
                    );
                end
            end
            else begin
                skipped = skipped + 1;
                $display(
                    "SKIP at t=%0t addr=%0d (uninitialized location)",
                    $time, address
                );
            end
        end
    endtask

