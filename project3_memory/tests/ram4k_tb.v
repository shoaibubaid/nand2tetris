    // NAND2Tetris tick: rising clock edge.
    task tick;
        begin
            #1;
            clk = 1'b1;
            #1;
            if (load === 1'b1) begin
                expected_mem[address] = in;
                valid[address] = 1'b1;
            end
        end
    endtask

    // NAND2Tetris tock: falling clock edge.
    task tock;
        begin
            #1;
            clk = 1'b0;
            #1;
        end
    endtask

    // Allow combinational outputs to settle after changing address.
    task eval_output;
        begin
            #1;
        end
    endtask

